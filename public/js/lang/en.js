function tr(s) {
  if (s == null) return s;
  const str = String(s);
  const lead = str.match(/^\s*/)[0];
  const tail = str.match(/\s*$/)[0];
  const core = str.trim();
  if (!core || !/[가-힣]/.test(core)) return str;
  if (TEXT[core] != null) return lead + TEXT[core] + tail;
  for (const [re, rep] of PATTERNS) {
    if (re.test(core)) return lead + core.replace(re, rep) + tail;
  }
  return str;
}

